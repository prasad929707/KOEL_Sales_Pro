  width_mm                 INTEGER,
  height_mm                INTEGER,
  wet_weight_kg            INTEGER,
  def_tank_litres          NUMERIC(6,1),
  std_fuel_tank_litres     INTEGER,
  service_interval         TEXT,
  governing_system         TEXT,
  genset_controller        TEXT,
  frequency_hz             INTEGER       DEFAULT 50,
  voltage_v                INTEGER       DEFAULT 415,
  sound_level_db           TEXT,
  engine_length_mm         INTEGER,
  engine_width_mm          INTEGER,
  engine_height_mm         INTEGER,
  exhaust_pipe_size_inches NUMERIC(4,1),
  mean_piston_speed_ms     NUMERIC(5,2),
  exhaust_temp_celsius     TEXT,
  alternator_make          TEXT,
  alternator_efficiency_pct NUMERIC(5,1),
  insulation_class         TEXT          DEFAULT 'H',
  after_treatment          TEXT,
  fuel_injection           TEXT,
  silencer_location        TEXT,
  source_label             TEXT,
  source_url               TEXT,
  remarks                  TEXT,
  created_at               TIMESTAMPTZ   DEFAULT NOW(),

  UNIQUE (kva_rating, brand)
);

-- Row Level Security
ALTER TABLE competitor_specs ENABLE ROW LEVEL SECURITY;

